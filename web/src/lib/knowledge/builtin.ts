export const BUILTIN_ENTRIES: KnowledgeEntry[] = DATA.map((d) => ({
  ...d,
  slug: normalizeName(d.name),
  source: "builtin",
  updatedAt: BUILTIN_UPDATED_AT,
}));

/** 正規化後的別名表：alias → entry（名稱本身也算別名） */
const ALIAS_INDEX: { alias: string; entry: KnowledgeEntry }[] = BUILTIN_ENTRIES.flatMap((entry) =>
  [entry.name, ...entry.aliases].map((a) => ({ alias: normalizeName(a), entry })),
).filter((x) => x.alias.length > 0);

export const BUILTIN_ALIASES: string[] = ALIAS_INDEX.map((x) => x.alias);

export function builtinByAlias(normalizedAlias: string): KnowledgeEntry | null {
  return ALIAS_INDEX.find((x) => x.alias === normalizedAlias)?.entry ?? null;
}

export function builtinBySlug(slug: string): KnowledgeEntry | null {
  return BUILTIN_ENTRIES.find((e) => e.slug === slug) ?? null;
}
